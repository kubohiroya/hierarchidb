import { resolveSpecifierExpression, resolveTargetSpecifier } from './entry-resolver.js';
import type { ManifestSummary, PluginSpecifierMode } from './types.js';

function indentJSON(value: unknown, indent: number): string {
  const json = JSON.stringify(value, null, 2);
  if (!json.includes('\n')) return json;
  const indentation = ' '.repeat(indent);
  return json.replace(/\n/g, `\n${indentation}`);
}

function formatModuleInfo(
  specifierExpr: string,
  options: { source?: string | null; exportName?: string } = {}
): string {
  const lines: string[] = ['{', `        specifier: ${specifierExpr},`];
  if (options.source) {
    lines.push(`        source: ${JSON.stringify(options.source)},`);
  }
  if (options.exportName) {
    lines.push(`        exportName: ${JSON.stringify(options.exportName)},`);
  }
  lines.push('      }');
  return lines.join('\n');
}

function hasWorkerModule(summary: ManifestSummary, mode: PluginSpecifierMode): boolean {
  if (!summary.hasWorker) return false;
  if (summary.workerSourceEntry) return true;
  return mode === 'dist-url' && Boolean(summary.workerDistEntry);
}

function formatModulesLiteral(summary: ManifestSummary, mode: PluginSpecifierMode): string {
  const entries: string[] = [];
  const rootSpecifier = resolveSpecifierExpression(
    summary.packageName,
    summary.rootDistEntry,
    mode
  );
  entries.push(`    root: ${formatModuleInfo(rootSpecifier)}`);

  if (summary.hasUI && (summary.uiSourceEntry || summary.uiDistEntry)) {
    const specExpr = resolveSpecifierExpression(
      `${summary.packageName}/ui`,
      summary.uiDistEntry,
      mode
    );
    entries.push(`    ui: ${formatModuleInfo(specExpr, { source: summary.uiSourceEntry })}`);
  }

  if (hasWorkerModule(summary, mode)) {
    const specExpr = resolveSpecifierExpression(
      `${summary.packageName}/worker`,
      summary.workerDistEntry,
      mode
    );
    entries.push(
      `    worker: ${formatModuleInfo(specExpr, { source: summary.workerSourceEntry })}`
    );
  }

  if (summary.hasDatabaseModule && (summary.databaseSourceEntry || summary.databaseDistEntry)) {
    const specExpr = resolveSpecifierExpression(
      `${summary.packageName}/database`,
      summary.databaseDistEntry,
      mode
    );
    entries.push(
      `    database: ${formatModuleInfo(specExpr, { source: summary.databaseSourceEntry })}`
    );
  }

  if (summary.hasCommon && (summary.commonSourceEntry || summary.commonDistEntry)) {
    const specExpr = resolveSpecifierExpression(
      `${summary.packageName}/common`,
      summary.commonDistEntry,
      mode
    );
    entries.push(
      `    common: ${formatModuleInfo(specExpr, { source: summary.commonSourceEntry })}`
    );
  }

  if (summary.iconComponent) {
    const icon = summary.iconComponent;
    const iconSpecExpr = resolveSpecifierExpression(icon.specifier, icon.distEntry ?? null, mode);
    entries.push(
      `    icon: ${formatModuleInfo(iconSpecExpr, { source: icon.sourceEntry, exportName: icon.exportName })}`
    );
  }

  return entries.length > 0
    ? `{
${entries.join(',\n')}
  }`
    : '{}';
}

export function generateRegistrySource(
  summaries: ManifestSummary[],
  mode: PluginSpecifierMode
): string {
  const entries = summaries
    .map((summary) => {
      const version = summary.manifest.version ?? summary.packageVersion;
      const dependenciesJSON = indentJSON(summary.dependencies, 6);
      const manifestJSON = indentJSON(summary.manifest ?? null, 6);
      const modulesLiteral = formatModulesLiteral(summary, mode);

      return `  {\n    nodeType: ${JSON.stringify(summary.nodeType)},\n    packageName: ${JSON.stringify(summary.packageName)},\n    version: ${JSON.stringify(version)},\n    dependencies: ${dependenciesJSON},\n    exports: ${JSON.stringify(summary.exportPaths)},\n    manifest: ${manifestJSON},\n    modules: ${modulesLiteral}\n  },`;
    })
    .join('\n');

  return `/* auto-generated by tools-build-scripts */\n/// <reference path="./registry.modules.d.ts" />\nimport type { PluginRegistryEntry } from '../src/types.js';\n\nexport const pluginRegistry: PluginRegistryEntry[] = [\n${entries}\n];\n`;
}

